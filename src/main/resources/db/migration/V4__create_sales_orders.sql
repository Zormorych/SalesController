CREATE SEQUENCE sales_order_number_seq START WITH 1;

CREATE TABLE sales_orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(20)  NOT NULL,
    customer_id  BIGINT       NOT NULL,
    order_date   DATE         NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    notes        VARCHAR(500),
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL,
    CONSTRAINT uk_sales_orders_number UNIQUE (order_number),
    CONSTRAINT fk_sales_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);

CREATE INDEX ix_sales_orders_customer ON sales_orders (customer_id);
CREATE INDEX ix_sales_orders_date ON sales_orders (order_date);

CREATE TABLE sales_order_lines (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id     BIGINT         NOT NULL,
    product_id         BIGINT         NOT NULL,
    product_name       VARCHAR(120)   NOT NULL,
    kit_name           VARCHAR(160)   NOT NULL,
    -- "size" y "value" se evitan como nombres de columna: son palabras reservadas en H2/PostgreSQL
    clothing_size      VARCHAR(20)    NOT NULL,
    unit_sale_price    NUMERIC(10, 2) NOT NULL,
    unit_purchase_cost NUMERIC(10, 2) NOT NULL,
    status             VARCHAR(20)    NOT NULL,
    CONSTRAINT fk_sales_order_lines_order FOREIGN KEY (sales_order_id) REFERENCES sales_orders (id),
    CONSTRAINT fk_sales_order_lines_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_sales_order_lines_sale_price CHECK (unit_sale_price >= 0),
    CONSTRAINT ck_sales_order_lines_purchase_cost CHECK (unit_purchase_cost >= 0)
);

CREATE INDEX ix_sales_order_lines_order ON sales_order_lines (sales_order_id);
CREATE INDEX ix_sales_order_lines_status ON sales_order_lines (status);

CREATE TABLE line_customizations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_line_id BIGINT         NOT NULL,
    customization_id    BIGINT         NOT NULL,
    customization_name  VARCHAR(120)   NOT NULL,
    custom_text         VARCHAR(120),
    sale_price          NUMERIC(10, 2) NOT NULL,
    purchase_cost       NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_line_customizations_line FOREIGN KEY (sales_order_line_id) REFERENCES sales_order_lines (id),
    CONSTRAINT fk_line_customizations_customization FOREIGN KEY (customization_id) REFERENCES customizations (id),
    CONSTRAINT ck_line_customizations_sale_price CHECK (sale_price >= 0),
    CONSTRAINT ck_line_customizations_purchase_cost CHECK (purchase_cost >= 0)
);

CREATE INDEX ix_line_customizations_line ON line_customizations (sales_order_line_id);
