CREATE SEQUENCE factory_batch_number_seq START WITH 1;

CREATE TABLE factory_batches (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_number  VARCHAR(20)    NOT NULL,
    status        VARCHAR(20)    NOT NULL,
    shipping_cost NUMERIC(10, 2) NOT NULL,
    notes         VARCHAR(500),
    sent_at       TIMESTAMP,
    created_at    TIMESTAMP      NOT NULL,
    updated_at    TIMESTAMP      NOT NULL,
    CONSTRAINT uk_factory_batches_number UNIQUE (batch_number),
    CONSTRAINT ck_factory_batches_shipping_cost CHECK (shipping_cost >= 0)
);

CREATE TABLE factory_batch_lines (
    factory_batch_id    BIGINT NOT NULL,
    sales_order_line_id BIGINT NOT NULL,
    CONSTRAINT pk_factory_batch_lines PRIMARY KEY (factory_batch_id, sales_order_line_id),
    -- Una camiseta solo puede estar en un lote a la vez
    CONSTRAINT uk_factory_batch_lines_line UNIQUE (sales_order_line_id),
    CONSTRAINT fk_factory_batch_lines_batch FOREIGN KEY (factory_batch_id) REFERENCES factory_batches (id),
    CONSTRAINT fk_factory_batch_lines_line FOREIGN KEY (sales_order_line_id) REFERENCES sales_order_lines (id)
);
