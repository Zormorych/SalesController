-- Stock y reventa: prendas compradas para revender (Vinted...) y camisetas de pedidos que el cliente ya no quiso
CREATE TABLE resale_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(160)   NOT NULL,
    -- "size" se evita como nombre de columna: es palabra reservada en H2/PostgreSQL
    item_size           VARCHAR(40),
    notes               VARCHAR(500),
    origin              VARCHAR(20)    NOT NULL,
    sales_order_line_id BIGINT,
    purchase_cost       NUMERIC(10, 2) NOT NULL,
    purchase_date       DATE           NOT NULL,
    asking_price        NUMERIC(10, 2),
    status              VARCHAR(20)    NOT NULL,
    sale_price          NUMERIC(10, 2),
    sale_date           DATE,
    created_at          TIMESTAMP      NOT NULL,
    updated_at          TIMESTAMP      NOT NULL,
    CONSTRAINT uk_resale_items_line UNIQUE (sales_order_line_id),
    CONSTRAINT fk_resale_items_line FOREIGN KEY (sales_order_line_id) REFERENCES sales_order_lines (id),
    CONSTRAINT ck_resale_items_purchase_cost CHECK (purchase_cost >= 0),
    CONSTRAINT ck_resale_items_asking_price CHECK (asking_price >= 0),
    CONSTRAINT ck_resale_items_sale_price CHECK (sale_price >= 0)
);

CREATE INDEX ix_resale_items_status ON resale_items (status);
